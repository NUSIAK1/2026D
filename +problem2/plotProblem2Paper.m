%% ========================================================================
%  图 2：时空运输图
% ========================================================================

function f = drawSpaceTime(trips,boxes)

f = newFigure(24,16);

ax = axes( ...
    f, ...
    'Position',[0.11 0.13 0.84 0.80] ...
);

hold(ax,'on');


for y = 0:15

    if mod(y,2) == 0

        patch( ...
            ax, ...
            [ ...
                0, ...
                max(trips.Return_s)/3600*1.04, ...
                max(trips.Return_s)/3600*1.04, ...
                0 ...
            ], ...
            [ ...
                y-0.48, ...
                y-0.48, ...
                y+0.48, ...
                y+0.48 ...
            ], ...
            [0.96 0.98 0.99], ...
            'EdgeColor','none', ...
            'FaceAlpha',0.65 ...
        );

    end

end


for k = 1:height(trips)

    route = split( ...
        string(trips.Route(k)), ...
        "->" ...
    );


    t = [trips.Start_s(k)];
    y = [0];

    sizes = [];
    hard = [];


    for j = 1:numel(route)

        match = ...
            string(boxes.TripID) == string(trips.TripID(k)) & ...
            string(boxes.ServiceID) == route(j);


        assert( ...
            any(match), ...
            '架次 %s 在 %s 没有逐箱送达记录。', ...
            string(trips.TripID(k)), ...
            route(j) ...
        );


        values = unique( ...
            boxes.Delivery_s(match) ...
        );


        assert( ...
            max(values)-min(values) < 1e-5, ...
            '同一次投送的送达时刻不一致。' ...
        );


        t(end+1) = values(1); %#ok<AGROW>

        y(end+1) = str2double( ...
            extractAfter(route(j),1) ...
        ); %#ok<AGROW>


        sizes(end+1) = sum(match); %#ok<AGROW>

        hard(end+1) = any( ...
            isfinite(boxes.HardDeadline_s(match)) ...
        ); %#ok<AGROW>

    end


    t(end+1) = trips.Return_s(k);
    y(end+1) = 0;


    c = modelColor(trips.Model(k));

    faded = 0.20 + 0.80*c;


    plot( ...
        ax, ...
        t/3600, ...
        y, ...
        'Color',faded, ...
        'LineWidth',1.15 ...
    );


    for j = 1:numel(route)

        edge = [0.18 0.25 0.32];


        if hard(j)
            edge = [0.72 0.22 0.18];
        end


        scatter( ...
            ax, ...
            t(j+1)/3600, ...
            y(j+1), ...
            25+13*sizes(j), ...
            'o', ...
            'filled', ...
            'MarkerFaceColor',c, ...
            'MarkerEdgeColor',edge, ...
            'LineWidth',0.9 ...
        );

    end

end


xline( ...
    ax, ...
    max(trips.Return_s)/3600, ...
    ':', ...
    'Color',[0.40 0.44 0.49], ...
    'LineWidth',1.1 ...
);


ylim(ax,[-0.55 15.6]);

xlim( ...
    ax, ...
    [0 max(trips.Return_s)/3600*1.05] ...
);


yticks(ax,0:15);

yticklabels( ...
    ax, ...
    ["O01";"S"+compose('%03d',1:15)'] ...
);


styleAxes(ax);

grid(ax,'on');


xlabel(ax,'任务开始后的时间 / h');
ylabel(ax,'调度中心与服务区');


h = gobjects(1,4);

models = ["A","B","C"];


for k = 1:3

    h(k) = plot( ...
        ax, ...
        nan, ...
        nan, ...
        '-', ...
        'Color',modelColor(models(k)), ...
        'LineWidth',2 ...
    );

end


h(4) = scatter( ...
    ax, ...
    nan, ...
    nan, ...
    40, ...
    'o', ...
    'MarkerEdgeColor',[0.72 0.22 0.18] ...
);


legend( ...
    ax, ...
    h, ...
    {'A 型','B 型','C 型','含硬时限货箱的投送'}, ...
    'Location','northoutside', ...
    'Orientation','horizontal', ...
    'Box','off', ...
    'FontSize',8 ...
);


end


%% ========================================================================
%  图 3：逐箱时限矩阵
% ========================================================================

function f = drawDeadlineMatrix(boxes)

f = newFigure(25,16);

ax = axes( ...
    f, ...
    'Position',[0.085 0.13 0.77 0.78] ...
);

hold(ax,'on');


services = "S" + compose('%03d',1:15)';

counts = zeros(15,1);


for i = 1:15

    counts(i) = sum( ...
        string(boxes.ServiceID) == services(i) ...
    );

end


ncol = max(counts);


margin = nan(15,ncol);

medical = false(15,ncol);

first = false(15,ncol);

labels = strings(15,ncol);


for i = 1:15

    ix = find( ...
        string(boxes.ServiceID) == services(i) ...
    );


    target = boxes.HardDeadline_s(ix);


    target(~isfinite(target)) = ...
        boxes.ExpectedDeadline_s( ...
            ix(~isfinite(target)) ...
        );


    order = sortrows( ...
        [ ...
            (1:numel(ix))', ...
            target, ...
            -boxes.Priority(ix), ...
            boxes.Delivery_s(ix) ...
        ], ...
        [2 3 4] ...
    );


    ix = ix(order(:,1));

    target = target(order(:,1));


    for j = 1:numel(ix)

        margin(i,j) = ...
            ( ...
                target(j) - ...
                boxes.Delivery_s(ix(j)) ...
            ) / 60;


        medical(i,j) = logical( ...
            boxes.IsMedical(ix(j)) ...
        );


        first(i,j) = logical( ...
            boxes.IsFirst(ix(j)) ...
        );


        id = string( ...
            boxes.BoxID(ix(j)) ...
        );


        parts = split(id,'-');

        prefix = extractBefore( ...
            parts(2), ...
            2 ...
        );


        labels(i,j) = ...
            prefix + parts(3);

    end

end


transformed = ...
    sign(margin) .* sqrt(abs(margin));


mxNeg = max( ...
    30, ...
    ceil( ...
        max( ...
            0, ...
            -min(margin,[],'all','omitnan') ...
        ) / 15 ...
    ) * 15 ...
);


mxPos = max( ...
    60, ...
    ceil( ...
        max(margin,[],'all','omitnan') / 30 ...
    ) * 30 ...
);


set( ...
    ax, ...
    'Color',[0.94 0.95 0.96] ...
