function files = plotProblem2Paper(configFile,outputDir)
%PLOTPROBLEM2PAPER 根据 Excel 方案选择生成问题二的七张论文插图。
%
% 使用方法：
%   修改：
%       结果/问题二_绘图配置.xlsx
%
%   工作表：
%       绘图设置
%
%   单元格 B2 可选择：
%       TimelinessFirst
%       MakespanFirst
%       EnergyFirst
%       TripCountFirst
%       Balanced
%
%   图片将自动添加对应中文方案后缀，例如：
%       无人机甘特图_及时性优先.png
%       无人机甘特图_完成时间优先.png
%       无人机甘特图_能耗优先.png
%       无人机甘特图_架次数优先.png
%       无人机甘特图_折中方案.png
%
%   B3 填写结果目录下的分析表文件名。
%
% 从"代码"目录运行：
%   files = problem2.plotProblem2Paper();
%
% 本程序只生成 PNG，不生成 PDF。


%% ===================== 1. 路径设置 =====================

codeDir = fileparts(fileparts(mfilename('fullpath')));
rootDir = fileparts(codeDir);

resultDir = fullfile(rootDir,'结果');


% 默认配置文件
if nargin < 1 || isempty(configFile)
    configFile = fullfile( ...
        resultDir, ...
        '问题二_绘图配置.xlsx' ...
    );
end


% 默认图片输出目录
if nargin < 2 || isempty(outputDir)
    outputDir = fullfile( ...
        rootDir, ...
        '论文', ...
        '图表', ...
        '问题二' ...
    );
end


% 如果输出文件夹不存在，则自动创建
if ~isfolder(outputDir)
    mkdir(outputDir);
end


% 检查配置文件
assert( ...
    isfile(configFile), ...
    '缺少绘图配置表：%s', ...
    configFile ...
);


%% ===================== 2. 读取绘图方案 =====================

rawChoice = readcell( ...
    configFile, ...
    'Sheet','绘图设置', ...
    'Range','B2' ...
);

choice = strtrim(string(rawChoice{1}));


% 五种方案英文名称
validNames = [ ...
    "TimelinessFirst", ...
    "MakespanFirst", ...
    "EnergyFirst", ...
    "TripCountFirst", ...
    "Balanced" ...
];


% 对应中文后缀
suffixNames = [ ...
    "及时性优先", ...
    "完成时间优先", ...
    "能耗优先", ...
    "架次数优先", ...
    "折中方案" ...
];


% 查找当前方案
idxChoice = find( ...
    choice == validNames, ...
    1 ...
);


assert( ...
    isscalar(choice) && ~isempty(idxChoice), ...
    '绘图设置!B2 中的方案名称无效：%s', ...
    choice ...
);


% 当前中文方案名称
schemeSuffix = suffixNames(idxChoice);


fprintf('\n');
fprintf('========================================\n');
fprintf('当前选择方案：%s\n',choice);
fprintf('中文方案名称：%s\n',schemeSuffix);
fprintf('========================================\n\n');


%% ===================== 3. 读取分析表文件名 =====================

rawSource = readcell( ...
    configFile, ...
    'Sheet','绘图设置', ...
    'Range','B3' ...
);

sourceName = strtrim(string(rawSource{1}));


assert( ...
    isscalar(sourceName) && strlength(sourceName) > 0, ...
    '绘图设置!B3 需要填写结果目录下的分析表文件名。' ...
);


analysisFile = fullfile( ...
    resultDir, ...
    sourceName ...
);


assert( ...
    isfile(analysisFile), ...
    '缺少问题二分析表：%s', ...
    analysisFile ...
);


%% ===================== 4. 原始数据文件 =====================

nodeFile = fullfile( ...
    rootDir, ...
    '原始题目信息', ...
    '数据', ...
    '无人机应急物资运输基础数据', ...
    '调度中心与服务区.xlsx' ...
);


demFile = fullfile( ...
    rootDir, ...
    '原始题目信息', ...
    '数据', ...
    '镇龙乡地理空间数据', ...
    '镇龙乡及周边地理数据', ...
    '数字高程模型数据（DEM）', ...
    '镇龙乡及周边30米DEM.mat' ...
);


%% ===================== 5. 读取问题二分析结果 =====================

summary = readtable( ...
    analysisFile, ...
    'Sheet','代表方案汇总' ...
);

front = readtable( ...
    analysisFile, ...
    'Sheet','Pareto前沿' ...
);

tripsAll = readtable( ...
    analysisFile, ...
    'Sheet','代表方案架次' ...
);

boxesAll = readtable( ...
    analysisFile, ...
    'Sheet','代表方案逐箱交付' ...
);


%% ===================== 6. 根据 B2 自动选择方案 =====================

trips = tripsAll( ...
    string(tripsAll.Representative) == choice, ...
    : ...
);

boxes = boxesAll( ...
    string(boxesAll.Representative) == choice, ...
    : ...
);

selected = summary( ...
    string(summary.Representative) == choice, ...
    : ...
);


assert( ...
    height(selected) == 1 && ...
    ~isempty(trips) && ...
    ~isempty(boxes), ...
    '分析表未包含方案 %s 的完整数据。', ...
    choice ...
);


assert( ...
    numel(unique(string(boxes.BoxID))) == height(boxes), ...
    '逐箱交付表存在重复货箱编号。' ...
);


assert( ...
    all(ismember( ...
        string(boxes.TripID), ...
        string(trips.TripID) ...
    )), ...
    '逐箱交付与架次表的 TripID 不一致。' ...
);


assert( ...
    abs(max(trips.Return_s) - selected.Makespan_s) < 1e-4, ...
    '架次表与方案汇总的完成时间不一致。' ...
);


assert( ...
    abs(sum(trips.Energy_kWh) - selected.Energy_kWh) < 1e-4, ...
    '架次表与方案汇总的能耗不一致。' ...
);


%% ===================== 7. 读取节点与 DEM =====================

nodes = loadNodes(nodeFile);

dem = load( ...
    demFile, ...
    'dem', ...
    'latitude', ...
    'longitude', ...
    'nodata' ...
);

dem.dem(dem.dem == dem.nodata) = NaN;


%% ===================== 8. 中文字体 =====================

oldFont = get(groot,'defaultAxesFontName');

fontCleanup = onCleanup( ...
    @()set(groot,'defaultAxesFontName',oldFont) ...
); %#ok<NASGU>

set( ...
    groot, ...
    'defaultAxesFontName', ...
    'Microsoft YaHei' ...
);


%% ===================== 9. 绘制七张图 =====================

names = { ...
    '地形路线图', ...
    '时空运输图', ...
    '逐箱时限矩阵', ...
    '电池SOC图', ...
    'Pareto权衡图', ...
    '无人机甘特图', ...
    '电池甘特图' ...
};


figures = cell(1,7);

figures{1} = drawRouteMap( ...
    trips, ...
    boxes, ...
    nodes, ...
    dem ...
);

figures{2} = drawSpaceTime( ...
    trips, ...
    boxes ...
);

figures{3} = drawDeadlineMatrix( ...
    boxes ...
);

figures{4} = drawBatterySOC( ...
    trips ...
);

figures{5} = drawPareto( ...
    front, ...
    summary, ...
    choice ...
);

figures{6} = drawDroneGantt( ...
    trips ...
);

figures{7} = drawBatteryGantt( ...
    trips ...
);


%% ===================== 10. 保存 PNG =====================

% 只保存 PNG
files = strings(7,1);


for k = 1:7

    % 文件名，例如：
    % 无人机甘特图_折中方案.png
    baseName = ...
        string(names{k}) + ...
        "_" + ...
        schemeSuffix;


    pngFile = fullfile( ...
        outputDir, ...
        baseName + ".png" ...
    );


    exportgraphics( ...
        figures{k}, ...
        pngFile, ...
        'Resolution',400, ...
        'BackgroundColor','white' ...
    );


    close(figures{k});


    files(k) = string(pngFile);

end


%% ===================== 11. 输出信息 =====================

fprintf('\n');
fprintf('========================================\n');
fprintf('问题二论文图已生成\n');
fprintf('方案英文名称：%s\n',choice);
fprintf('方案中文名称：%s\n',schemeSuffix);
fprintf('图片输出目录：%s\n',outputDir);
fprintf('========================================\n\n');

disp(files);


end


%% ========================================================================
%  读取节点
% ========================================================================

function nodes = loadNodes(path)

c = readcell( ...
    path, ...
    'Sheet','数据' ...
);

ids = string(c(:,1));


keep = ...
    ids == "O01" | ...
    ~cellfun( ...
        @isempty, ...
        regexp( ...
            cellstr(ids), ...
            '^S\d{3}$', ...
            'once' ...
        ) ...
    );


rows = c(keep,:);


nodes = table( ...
    string(rows(:,1)), ...
    zeros(size(rows,1),1), ...
    zeros(size(rows,1),1), ...
    'VariableNames', ...
    {'ID','Lon','Lat'} ...
);


for k = 1:height(nodes)

    nodes.Lon(k) = double(rows{k,3});
    nodes.Lat(k) = double(rows{k,4});

end


assert( ...
    height(nodes) == 16 && ...
    numel(unique(nodes.ID)) == 16, ...
    '节点数据需要包含 O01 和 S001 至 S015。' ...
);


end


%% ========================================================================
%  机型颜色
% ========================================================================

function color = modelColor(model)

switch string(model)

    case "A"
        color = [0.13 0.38 0.67];

    case "B"
        color = [0.02 0.55 0.49];

    case "C"
        color = [0.79 0.34 0.16];

    otherwise
        error( ...
            '未知机型：%s', ...
            string(model) ...
        );

end

end


