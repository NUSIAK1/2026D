%% ========================================================================
%  图 1：地形路线图
% ========================================================================

function f = drawRouteMap(trips,boxes,nodes,dem)

f = newFigure(23,16);

ax = axes( ...
    f, ...
    'Position',[0.10 0.11 0.74 0.81] ...
);

hold(ax,'on');


stride = 3;

elev = double( ...
    dem.dem( ...
        1:stride:end, ...
        1:stride:end ...
    ) ...
);

lon = dem.longitude(1:stride:end);
lat = dem.latitude(1:stride:end);


im = imagesc( ...
    ax, ...
    [lon(1),lon(end)], ...
    [lat(end),lat(1)], ...
    flipud(elev) ...
);


set( ...
    im, ...
    'AlphaData', ...
    double(~isnan(elev(end:-1:1,:))) * 0.88 ...
);


set(ax,'YDir','normal');

colormap(ax,terrainColors());


validElev = elev(~isnan(elev));

clim( ...
    ax, ...
    prctile(validElev,[3 97]) ...
);


padLon = 0.017;
padLat = 0.014;


xlim( ...
    ax, ...
    [ ...
        min(nodes.Lon)-padLon, ...
        max(nodes.Lon)+padLon ...
    ] ...
);


ylim( ...
    ax, ...
    [ ...
        min(nodes.Lat)-padLat, ...
        max(nodes.Lat)+padLat ...
    ] ...
);


from = strings(0,1);
to = strings(0,1);
model = strings(0,1);
count = zeros(0,1);


for k = 1:height(trips)

    stops = split( ...
        string(trips.Route(k)), ...
        "->" ...
    );

    path = [ ...
        "O01"; ...
        stops; ...
        "O01" ...
    ];


    for j = 1:numel(path)-1

        idx = find( ...
            from == path(j) & ...
            to == path(j+1) & ...
            model == string(trips.Model(k)), ...
            1 ...
        );


        if isempty(idx)

            from(end+1,1) = path(j); %#ok<AGROW>
            to(end+1,1) = path(j+1); %#ok<AGROW>

            model(end+1,1) = ...
                string(trips.Model(k)); %#ok<AGROW>

            count(end+1,1) = 1; %#ok<AGROW>

        else

            count(idx) = count(idx) + 1;

        end

    end

end


for k = 1:numel(count)

    a = find( ...
        nodes.ID == from(k), ...
        1 ...
    );

    b = find( ...
        nodes.ID == to(k), ...
        1 ...
    );


    assert( ...
        ~isempty(a) && ~isempty(b), ...
        '路线包含未知节点。' ...
    );


    dx = nodes.Lon(b) - nodes.Lon(a);
    dy = nodes.Lat(b) - nodes.Lat(a);


    c = modelColor(model(k));

    c = 0.13 + 0.87*c;


    plot( ...
        ax, ...
        [nodes.Lon(a),nodes.Lon(b)], ...
        [nodes.Lat(a),nodes.Lat(b)], ...
        'Color',c, ...
        'LineWidth',0.95 + 0.65*sqrt(count(k)) ...
    );


    midx = nodes.Lon(a) + 0.57*dx;
    midy = nodes.Lat(a) + 0.57*dy;


    quiver( ...
        ax, ...
        midx-0.045*dx, ...
        midy-0.045*dy, ...
        0.09*dx, ...
        0.09*dy, ...
        0, ...
        'Color',c, ...
        'LineWidth',1.4, ...
        'MaxHeadSize',2, ...
        'AutoScale','off' ...
    );

end


for k = 1:height(nodes)

    id = nodes.ID(k);


    if id == "O01"

        scatter( ...
            ax, ...
            nodes.Lon(k), ...
            nodes.Lat(k), ...
            210, ...
            'p', ...
            'filled', ...
            'MarkerFaceColor',[0.99 0.77 0.25], ...
            'MarkerEdgeColor',[0.15 0.20 0.27], ...
            'LineWidth',1.2 ...
        );


        text( ...
            ax, ...
            nodes.Lon(k)+0.003, ...
            nodes.Lat(k)-0.003, ...
            'O01', ...
            'FontWeight','bold', ...
            'FontSize',9, ...
            'Color',[0.12 0.18 0.23], ...
            'BackgroundColor','white', ...
            'Margin',1 ...
        );

    else

        n = sum( ...
            string(boxes.ServiceID) == id ...
        );


        scatter( ...
            ax, ...
            nodes.Lon(k), ...
            nodes.Lat(k), ...
            42+6*n, ...
            'o', ...
            'filled', ...
            'MarkerFaceColor',[0.96 0.98 0.99], ...
            'MarkerEdgeColor',[0.12 0.25 0.35], ...
            'LineWidth',1.1 ...
        );


        text( ...
            ax, ...
            nodes.Lon(k)+0.0025, ...
            nodes.Lat(k)+0.001, ...
            id, ...
            'FontSize',7.2, ...
            'Color',[0.10 0.20 0.28], ...
            'BackgroundColor','white', ...
            'Margin',0.5 ...
        );

    end

end


cb = colorbar( ...
    ax, ...
    'Position',[0.87 0.22 0.022 0.53] ...
);

cb.Label.String = '地面高程 / m';
cb.FontSize = 8;


styleAxes(ax);

grid(ax,'on');


xlabel(ax,'经度 / °E');
ylabel(ax,'纬度 / °N');

axis(ax,'equal');


handles = gobjects(1,3);

models = ["A","B","C"];


for k = 1:3

    handles(k) = plot( ...
        ax, ...
        nan, ...
        nan, ...
        'LineWidth',2.4, ...
        'Color',modelColor(models(k)) ...
    );

end


legend( ...
    ax, ...
    handles, ...
    {'A 型','B 型','C 型'}, ...
    'Location','southoutside', ...
    'Orientation','horizontal', ...
    'Box','off', ...
    'FontSize',8 ...
);


end


