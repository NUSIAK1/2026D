%  图 4：电池 SOC 图
% ========================================================================

function f = drawBatterySOC(trips)

f = newFigure(25,17);


tl = tiledlayout( ...
    f, ...
    3, ...
    1, ...
    'TileSpacing','compact', ...
    'Padding','compact' ...
);


models = ["A","B","C"];


tmax = max( ...
    trips.Return_s + ...
    trips.ChargeTime_s ...
) / 3600;


makespan = max( ...
    trips.Return_s ...
) / 3600;


for mi = 1:3

    ax = nexttile(tl);

    hold(ax,'on');


    modelTrips = trips( ...
        string(trips.Model) == models(mi), ...
        : ...
    );


    batteryIDs = unique( ...
        string(modelTrips.BatteryID), ...
        'stable' ...
    );


    base = modelColor(models(mi));


    legendHandles = ...
        gobjects(numel(batteryIDs),1);


    for bi = 1:numel(batteryIDs)

        b = batteryIDs(bi);


        bt = modelTrips( ...
            string(modelTrips.BatteryID) == b, ...
            : ...
        );


        bt = sortrows( ...
            bt, ...
            'Start_s' ...
        );


        shade = ...
            0.08 + ...
            0.45 * ...
            (bi-1) / ...
            max(1,numel(batteryIDs)-1);


        c = shade + (1-shade)*base;


        lastTime = 0;


        for k = 1:height(bt)

            start = bt.Start_s(k) / 3600;

            ret = bt.Return_s(k) / 3600;

            soc = bt.ReturnSOC_pct(k);

            ready = ...
                ( ...
                    bt.Return_s(k) + ...
                    bt.ChargeTime_s(k) ...
                ) / 3600;


            assert( ...
                start >= lastTime-1e-7, ...
                '电池 %s 的架次与充电重叠。', ...
                b ...
            );


            if k == 1

                plot( ...
                    ax, ...
                    [0 start], ...
                    [100 100], ...
                    '-', ...
                    'Color',c, ...
                    'LineWidth',1.3 ...
                );

            else

                plot( ...
                    ax, ...
                    [lastTime start], ...
                    [100 100], ...
                    '-', ...
                    'Color',c, ...
                    'LineWidth',1.3 ...
                );

            end


            plot( ...
                ax, ...
                [start ret], ...
                [100 soc], ...
                '--', ...
                'Color',c, ...
                'LineWidth',1.4 ...
            );


            if soc < 90-1e-8

                fastFraction = ...
                    0.65 * ...
                    (90-soc) / 90;


                totalFraction = ...
                    fastFraction + 0.35;


                t90 = ...
                    ret + ...
                    (ready-ret) * ...
                    fastFraction / ...
                    totalFraction;


                plot( ...
                    ax, ...
                    [ret t90 ready], ...
                    [soc 90 100], ...
                    '-', ...
                    'Color',c, ...
                    'LineWidth',1.5 ...
                );


                plot( ...
                    ax, ...
                    t90, ...
                    90, ...
                    'd', ...
                    'Color',c, ...
                    'MarkerFaceColor','white', ...
                    'MarkerSize',3.5, ...
                    'LineWidth',0.9 ...
                );

            else

                plot( ...
                    ax, ...
                    [ret ready], ...
                    [soc 100], ...
                    '-', ...
                    'Color',c, ...
                    'LineWidth',1.5 ...
                );

            end


            scatter( ...
                ax, ...
                ret, ...
                soc, ...
                21, ...
                'o', ...
                'filled', ...
                'MarkerFaceColor',c, ...
                'MarkerEdgeColor','white', ...
                'LineWidth',0.5 ...
            );


            lastTime = ready;

        end


        legendHandles(bi) = plot( ...
            ax, ...
            nan, ...
            nan, ...
            '-', ...
            'Color',c, ...
            'LineWidth',1.8, ...
            'DisplayName',char(b) ...
        );

    end


    yline( ...
        ax, ...
        90, ...
        ':', ...
        'Color',[0.52 0.57 0.62], ...
        'LineWidth',0.8 ...
    );


    xline( ...
        ax, ...
        makespan, ...
        ':', ...
        'Color',[0.50 0.53 0.57], ...
        'LineWidth',0.9 ...
    );


    xlim(ax,[0 tmax*1.03]);

    ylim(ax,[0 105]);


    yticks(ax,[0 25 50 75 90 100]);


    ylabel( ...
        ax, ...
        sprintf( ...
            '%s 型 SOC / %%', ...
            models(mi) ...
        ) ...
    );


    styleAxes(ax);

    grid(ax,'on');


    legend( ...
        ax, ...
        legendHandles, ...
        cellstr(batteryIDs), ...
        'Location','eastoutside', ...
        'Box','off', ...
        'FontSize',7.5 ...
    );

end


xlabel( ...
    tl, ...
    '任务开始后的时间 / h' ...
);


end


